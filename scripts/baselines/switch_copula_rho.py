def section_mle(rows, ii, jj):
    """Plan step 5 + half of the step-6 gate. Returns (rho_hat, ok)."""
    p, y = rows["p"], rows["y"]
    H, K, c, s = pair_terms(p, y, ii, jj)
    t0 = time.time()
    rho_hat, nll_hat, nll0, n_ev = rho_mle(H, K, c, s)
    dt = time.time() - t0
    ind = independence_nll(p, y, ii, jj)
    gap = abs(nll0 - ind)
    ok = gap <= NLL0_TOL
    print("\n=== rho: binary pairwise-likelihood MLE (train split) ===")
    print(f"rho_hat                      {f(rho_hat)}")
    print(f"  pairwise nll(rho_hat)      {f(nll_hat)}")
    print(f"  pairwise nll(0)            {f(nll0)}")
    print(
        f"  2*(nll(0) - nll(rho_hat))  {f(2.0 * (nll0 - nll_hat))}  "
        f"(pairwise LR, not chi2-calibrated)"
    )
    print(f"  n_pairs={len(ii)}  nll evals={n_ev}  fit {dt:.2f}s")
    print("\n=== GATE 1/2: pair_nll(0) vs the closed-form independence nll ===")
    print(f"  closed-form independence   {f(ind)}")
    print(f"  |difference|               {f(gap)}")
    print(f"  -> {'PASS' if ok else 'FAIL'} (tolerance {NLL0_TOL})")
    return rho_hat, ok


def section_roundtrip(rows):
    """Plan step 6: recovery of a known rho. Returns (rows, ok)."""
    t0 = time.time()
    table = roundtrip(rows)
    bias = max(abs(b) for _, _, b, _ in table)
    ok = bias <= BIAS_TOL
    print(
        f"\n=== GATE 2/2: round-trip recovery ({N_ROUNDTRIP} replicates per "
        f"rho, seed {SEED}) ==="
    )
    print("rho_true   mean rho_hat           bias                   sd")
    for rho_true, mean, b, sd in table:
        print(f"{rho_true:<10.2f} {f(mean):<22} {f(b):<22} {f(sd)}")
    print(
        f"max |bias| = {f(bias)}  -> {'PASS' if ok else 'FAIL'} "
        f"(tolerance {BIAS_TOL})   [{time.time() - t0:.1f}s]"
    )
    return table, ok


def section_bootstrap(rows, ii, jj, rho_hat, n_boot):
    """Plan step 7: SE / CI, the holdout check, and the diagnostic splits."""
    p, y = rows["p"], rows["y"]
    H, K, c, s = pair_terms(p, y, ii, jj)
    per_game = per_game_pairs(rows["game"], ii, jj)
    game_ids = np.array(sorted(per_game))
    t0 = time.time()
    (boot,) = bootstrap_games([(H, K, c, s, per_game)], game_ids, n_boot, SEED)
    se = float(boot.std(ddof=1))
    ci = (float(np.percentile(boot, 2.5)), float(np.percentile(boot, 97.5)))
    print(
        f"\n=== cluster bootstrap ({n_boot} resamples over {len(game_ids)} games) ==="
    )
    print(f"rho_hat                      {f(rho_hat)}")
    print(f"  SE                         {f(se)}")
    print(f"  95% percentile CI          [{f(ci[0])}, {f(ci[1])}]")
    print(
        f"  bootstrap min/max          {f(boot.min())} / {f(boot.max())}"
        f"   [{time.time() - t0:.1f}s]"
    )

    te = load_probs(PROBS["test"])
    rho_te, pr_te, rows_te, cells_te = mle_on_rows(te)
    print(
        f"\nOUT-OF-SAMPLE CHECK ONLY ({Path(te['path']).name}, games={te['n_games']})"
    )
    print(
        f"  rho={f(rho_te)}  rows={rows_te} cells>=2={cells_te} pairs={pr_te}"
        f"  (the marginal model saw all 50 games -- ruling D1)"
    )

    print("\n=== DIAGNOSTIC splits (never a selection criterion) ===")
    print("split                        rho                     n")

    def split(label, sel):
        rho, n_pr, n_rows, n_cells = mle_on_rows(rows, sel)
        print(
            f"{label:<28} {f(rho):<23} rows={n_rows} cells>=2={n_cells} "
            f"pairs={n_pr}"
        )

    for r in np.unique(rows["round"]):
        split(f"decision round {r}", rows["round"] == r)
    order, starts, sizes = blocks(rows["cell"])
    size_of_cell = dict(zip(rows["cell"][order][starts], sizes))
    row_size = np.array([size_of_cell[k] for k in rows["cell"]])
    split("cell size 2-3", np.isin(row_size, (2, 3)))
    split("cell size 4+", row_size >= 4)
    return se, ci


def section_lag1(rows, ii, jj, rho_hat, n_boot):
    """Plan step 8: rho_lag1, phi_hat, and the drop verdict."""
    p, y = rows["p"], rows["y"]
    ic, jc = cross_pairs(rows)
    same = int((rows["player"][ic] == rows["player"][jc]).sum())
    Hc, Kc, cc, sc = pair_terms(p, y, ic, jc)
    rho_lag1, nll_hat, nll0, _ = rho_mle(Hc, Kc, cc, sc)
    rho_signed = rho_mle(Hc, Kc, cc, sc, grid=RHO_GRID_SIGNED)[0]
    phi_hat = rho_lag1 / rho_hat if rho_hat > 0 else float("nan")
    print("\n=== arm B: lag-1 persistence of the group latent ===")
    print(
        f"cross-round pairs            {len(ic)}  "
        f"(same player at both rounds: {same})"
    )
    print(f"rho_lag1                     {f(rho_lag1)}")
    print(f"  pairwise nll(rho_lag1)     {f(nll_hat)}")
    print(f"  2*(nll(0) - nll(rho_lag1)) {f(2.0 * (nll0 - nll_hat))}")
    print(
        f"  signed-grid refit          {f(rho_signed)}  DIAGNOSTIC: "
        f"the estimate when rho < 0 is allowed (boundary check)"
    )
    print(f"phi_hat = rho_lag1 / rho_hat {f(phi_hat)}")

    H, K, c, s = pair_terms(p, y, ii, jj)
    pg_w = per_game_pairs(rows["game"], ii, jj)
    pg_c = per_game_pairs(rows["game"], ic, jc)
    game_ids = np.array(sorted(pg_w))
    t0 = time.time()
    bw, bc = bootstrap_games(
        [(H, K, c, s, pg_w), (Hc, Kc, cc, sc, pg_c)], game_ids, n_boot, SEED
    )
    phi_b = np.where(bw > 0, bc / np.where(bw > 0, bw, 1.0), np.nan)
    finite = phi_b[np.isfinite(phi_b)]
    ci = (float(np.percentile(finite, 2.5)), float(np.percentile(finite, 97.5)))
    keep, why = phi_verdict(phi_hat, ci)
    print(f"cluster bootstrap ({n_boot} resamples, rho and rho_lag1 refit per draw)")
    print(f"  phi 95% percentile CI      [{f(ci[0])}, {f(ci[1])}]  <- the drop rule")
    print(f"  phi bootstrap median       {f(np.median(finite))}")
    print(
        f"  phi SE                     {f(finite.std(ddof=1))}  "
        f"(a RATIO: heavy-tailed as the denominator approaches 0, no finite "
        f"moments -- read the percentile CI, not this)"
    )
    print(f"  degenerate draws (rho=0)   {int(len(phi_b) - len(finite))}")
    print(f"  draws with rho < 0.01      {int((bw < 0.01).sum())}")
    print(f"  rho bootstrap min/max      {f(bw.min())} / {f(bw.max())}")
    print(
        f"  rho_lag1 min/mean/max      {f(bc.min())} / {f(bc.mean())} / "
        f"{f(bc.max())}   [{time.time() - t0:.1f}s]"
    )
    print(f"VERDICT: {'ARM B KEPT' if keep else 'ARM B DROPPED -- ' + why}")
    return rho_lag1, phi_hat, ci, keep, why, len(ic)


