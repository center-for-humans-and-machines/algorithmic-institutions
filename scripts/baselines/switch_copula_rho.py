# --------------------------------------------------------------------------- #
# the conditional estimator: binary pairwise-likelihood MLE (plan step 5)
# --------------------------------------------------------------------------- #
def thresholds(p):
    """t = Phi^-1(1 - p), so P(z > t) = p = P(switch).

    Switching is the UPPER tail of the latent everywhere in this file --
    estimator, generator and (later) sampler share the orientation, so the
    round-trip of step 6 tests exactly the model that is fitted.
    """
    return ndtri(1.0 - p)


def pair_terms(p, y, ii, jj):
    """Rectangle constants of every pair: P(y_i, y_j | rho) = c + s * P11.

    P11 = P(z_i > t_i, z_j > t_j) = Phi_2(-t_i, -t_j; rho), hence
    (1,1): 0 + P11,  (1,0): p_i - P11,  (0,1): p_j - P11,
    (0,0): 1 - p_i - p_j + P11.
    Returns (H, K, c, s) with H = -t_i, K = -t_j. Only c and s depend on the
    outcomes, so a bootstrap resample or a synthetic outcome vector reuses
    the same corner points.
    """
    pi, pj = p[ii], p[jj]
    a, b = y[ii].astype(bool), y[jj].astype(bool)
    c = np.where(a & b, 0.0, np.where(a, pi, np.where(b, pj, 1.0 - pi - pj)))
    s = np.where(a == b, 1.0, -1.0)
    t = thresholds(p)
    return -t[ii], -t[jj], c, s


def pair_nll(H, K, c, s, rho):
    """Negative summed pairwise log-likelihood at `rho` (floored before log)."""
    prob = c + s * bvn_cdf(H, K, rho)
    return -float(np.log(np.maximum(prob, P_TINY)).sum())


def independence_nll(p, y, ii, jj):
    """Closed-form pairwise nll under independence -- what pair_nll(0) must
    reproduce: the sum of the two Bernoulli log-likelihoods of each pair."""
    q = np.where(y.astype(bool), p, 1.0 - p)
    return -float((np.log(q[ii]) + np.log(q[jj])).sum())


def rho_mle(H, K, c, s, grid=RHO_GRID):
    """Maximise the pairwise log-likelihood: coarse grid, then bounded Brent.
    Returns (rho_hat, nll(rho_hat), nll(0), n_evals)."""
    from scipy.optimize import minimize_scalar

    lo_b, hi_b = float(grid[0]), float(grid[-1])
    evals = [0]

    def nll(rho):
        evals[0] += 1
        return pair_nll(H, K, c, s, float(np.clip(rho, lo_b, hi_b)))

    vals = [nll(r) for r in grid]
    b = int(np.argmin(vals))
    lo = float(grid[max(b - 1, 0)])
    hi = float(grid[min(b + 1, len(grid) - 1)])
    res = minimize_scalar(
        nll, bounds=(lo, hi), method="bounded", options=dict(xatol=1e-6)
    )
    zero = np.flatnonzero(np.isclose(grid, 0.0))
    nll0 = vals[int(zero[0])] if len(zero) else nll(0.0)
    return float(res.x), float(res.fun), float(nll0), evals[0]


def mle_on_rows(rows, sel=None, grid=RHO_GRID):
    """(rho, n_pairs, n_rows, n_cells>=2) over a row subset's within-cell
    pairs -- pairs are rebuilt inside the subset, never inherited."""
    y = rows["y"]
    sel = np.ones(len(y), bool) if sel is None else sel
    p_s, y_s, cell_s = rows["p"][sel], y[sel], rows["cell"][sel]
    ii, jj = pair_index(cell_s)
    H, K, c, s = pair_terms(p_s, y_s, ii, jj)
    rho = rho_mle(H, K, c, s, grid=grid)[0]
    _, _, sizes = blocks(cell_s)
    return rho, len(ii), int(sel.sum()), int((sizes >= 2).sum())


# --------------------------------------------------------------------------- #
# cross-round pairs of one group's latent (plan step 8)
# --------------------------------------------------------------------------- #
def cross_pairs(rows, step=SWITCH_EVERY):
    """Row indices (i at decision round r, j at round r + step) belonging to
    the same (game, group) -- the lag-1 pairs whose model correlation is
    rho * phi.

    The block key is the GROUP's latent, so each row joins the block of the
    group it belonged to AT ITS OWN ROUND: a player who switched at r sits
    in the other group's block at r + step. Every i x j combination of the
    two blocks enters once, INCLUDING the same player at both rounds -- the
    per-agent noise is redrawn each round, so the implied correlation is
    rho * phi for every cross-round pair, same player or not. Only rounds
    exactly one decision epoch apart are paired.
    """
    idx = {}
    for pos, key in enumerate(
        zip(rows["game"].tolist(), rows["round"].tolist(), rows["group"].tolist())
    ):
        idx.setdefault(key, []).append(pos)
    ii, jj = [], []
    for (g, r, grp), a in sorted(idx.items()):
        b = idx.get((g, r + step, grp))
        if b is None:
            continue
        a_arr, b_arr = np.array(a, np.int64), np.array(b, np.int64)
        ii.append(np.repeat(a_arr, len(b_arr)))
        jj.append(np.tile(b_arr, len(a_arr)))
    if not ii:
        return np.array([], np.int64), np.array([], np.int64)
    return np.concatenate(ii), np.concatenate(jj)


def phi_verdict(phi_hat, ci):
    """The plan's drop rule for arm B: (kept?, reason)."""
    if not np.isfinite(phi_hat) or phi_hat <= 0.0:
        return False, f"phi_hat {f(phi_hat)} <= 0"
    if ci[0] <= 0.0 <= ci[1]:
        return False, f"95% CI [{f(ci[0])}, {f(ci[1])}] includes 0"
    return True, ""


# --------------------------------------------------------------------------- #
# cluster bootstrap over games
# --------------------------------------------------------------------------- #
def per_game_pairs(game, ii, jj):
    """{game: pair positions}; every pair sits inside a single game, so
    resampling games resamples whole pair blocks. Games contributing no
    pair map to an empty array."""
    g = game[ii]
    assert np.array_equal(g, game[jj]), "pair crosses games"
    return {int(k): np.flatnonzero(g == k) for k in np.unique(game)}


def bootstrap_games(pairsets, game_ids, n_boot, seed):
    """Cluster bootstrap over games. `pairsets` is a list of
    (H, K, c, s, per_game); all sets see the SAME game resample, so the
    returned rho arrays are paired and their ratio is a valid phi draw.

    Every resample is refit on the full RHO_GRID -- the precedent narrows
    the bracket around the full-sample estimate for cost, but 3009 pairs
    are cheap enough here and a narrowed bracket censored the upper tail.
    """
    rng = np.random.default_rng(seed)
    out = [np.empty(n_boot) for _ in pairsets]
    for b in range(n_boot):
        draw = rng.choice(game_ids, size=len(game_ids), replace=True)
        for o, (H, K, c, s, per_game) in zip(out, pairsets):
            pos = np.concatenate([per_game[int(g)] for g in draw])
            o[b] = rho_mle(H[pos], K[pos], c[pos], s[pos])[0]
    return out


# --------------------------------------------------------------------------- #
# round-trip acceptance gate (plan step 6)
# --------------------------------------------------------------------------- #
def sample_copula_binary(t, inv, n_cells, rho, rng):
    """Outcomes from exactly the model being estimated: one shared latent per
    cell at weight sqrt(rho), fresh per-agent noise, switch = upper tail.

    w = sqrt(rho) z_cell + sqrt(1 - rho) eps ~ N(0, 1) and y = 1[w > t] is
    the z-side form of `u = ndtr(w) > 1 - p` -- identical, minus one
    ndtr/Phi^-1 round-trip.
    """
    z = rng.standard_normal(n_cells)
    eps = rng.standard_normal(len(t))
    w = np.sqrt(rho) * z[inv] + np.sqrt(1.0 - rho) * eps
    return (w > t).astype(np.int64)


def roundtrip(rows, rho_trues=RHO_TRUES, n_rep=N_ROUNDTRIP, seed=SEED):
    """(rho_true, mean rho_hat, bias, sd) per rho_true, on the REAL dumped
    marginals and the REAL cell structure."""
    p, cell = rows["p"], rows["cell"]
    t = thresholds(p)
    _, inv = np.unique(cell, return_inverse=True)
    n_cells = int(inv.max()) + 1
    ii, jj = pair_index(cell)
    rng = np.random.default_rng(seed)
    out = []
    for rho_true in rho_trues:
        hats = np.empty(n_rep)
        for k in range(n_rep):
            y = sample_copula_binary(t, inv, n_cells, rho_true, rng)
            H, K, c, s = pair_terms(p, y, ii, jj)
            hats[k] = rho_mle(H, K, c, s)[0]
        out.append(
            (
                float(rho_true),
                float(hats.mean()),
                float(hats.mean() - rho_true),
                float(hats.std(ddof=1)),
            )
        )
    return out


