"""Seed ensemble vs the contribution copula: is parameter (epistemic)
uncertainty a plausible source of the shared per-group error the copula
compensates for?

The PR #181 stimulus-skip contributor trunk is retrained K times with
different seeds (config `..._vnode_stimulus_skip_seed_ensemble.yml`), every
member is teacher-forced on the human canonical frame (the loaders of
`contribution_copula_rho.py`: one copy per game, rows where
`contribution_valid`), and the K predicted marginals per agent-round are
compared:

  (a) between-seed disagreement per agent-round -- SD over seeds of the
      expected contribution, and the mean total-variation distance between
      seed distributions -- against the predictive spread of one model;
  (b) the shared part: within every (episode, round, group) cell, the
      correlation across group members of the seed deviations
      (E_k - ensemble mean), pair-weighted over cells, per seed; the same on
      the PIT / latent scale the copula uses (each seed's expected value
      mapped through the ensemble-mean model's CDF, then Phi^-1); and the
      copula script's own estimator run on synthetic data generated by
      "one seed per episode" sampling with the ensemble-mean marginal --
      the rho the calibration would fit if the human data had been produced
      by the ensemble-as-noise model;
  (c) persistence of the cell-level seed deviation across rounds, against
      the copula's phi = 1 (static episode latent).

Alongside: the human residual within-group correlation given the ensemble
mean (PR #140's decomposition, recomputed), and the copula rho refit on the
human data with the ensemble-mean marginal.

Measurement only; imports graph.py, so it needs torch_geometric (Raven):
    python scripts/data_analysis/copula_seed_ensemble.py \
        [--ensemble-dir DIR] [--shipped PT] [--out-dir DIR] [--n-syn 20]
"""

